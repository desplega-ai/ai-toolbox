export type IconName = keyof typeof PATHS;

function toSvg(paths: string): string {
  return `<svg class="icon-svg" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${paths}</svg>`;
}

/** Inline SVG markup per icon name, ready to drop into innerHTML. */
export const icons = Object.fromEntries(
  Object.entries(PATHS).map(([name, paths]) => [name, toSvg(paths)])
) as Record<IconName, string>;

/**
 * Fill every `[data-icon="name"]` placeholder under `root` with its SVG.
 * Lets static markup in index.html reference icons without duplicating paths.
 */
export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-icon]").forEach((el) => {
    const name = el.dataset.icon as IconName;
    if (name in icons) el.innerHTML = icons[name];
  });
}
